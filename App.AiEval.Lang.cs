        private static List<AiCase> InLanguage(List<AiCase> cases, string code)
        {
            var t = code == "es" ? Es : Pt;
            return cases
                .Where(c => c.Seq == null && c.Blocks == null && !c.Learn && c.Then == null && t.ContainsKey(c.Id))
                .Select(c => new AiCase { Id = code + "-" + c.Id, Prompt = t[c.Id], Setup = c.Setup, Select = c.Select, Check = c.Check })
                .ToList();
        }

